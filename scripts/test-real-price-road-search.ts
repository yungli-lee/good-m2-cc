import assert from 'node:assert/strict';
import {roadSearchPattern} from '../lib/real-price/road-search.ts';
const matches=(query:string,address:string,lanes=true)=>new RegExp(roadSearchPattern(query,lanes).replaceAll('[[:space:]　]*','\\s*')).test(address);
assert(matches('民族路','彰化縣彰化市民族路１２９巷１４號'));
assert(matches('公園路一段','彰化縣彰化市公園路一段１３３巷６號'));
for(const section of ['一','二','三','四','五','六','七','八']) assert(matches('彰鹿路',`彰化縣福興鄉彰鹿路${section}段123號`));
assert(!matches('彰鹿路二段','彰鹿路三段123號'));
assert(matches('彰鹿路2段','彰鹿路二段123號'));
assert(matches('彰鹿路二段','彰鹿路２段123號'));
assert(!matches('民族路','民族路129巷14號',false));
assert(matches('民族路','民族路14號',false));
assert(matches('彰鹿路','彰鹿路八段14號',false));
assert(!matches('彰鹿路','彰鹿路八段129巷14號',false));
assert(matches('民族路129巷','民族路１２９巷5弄14號',false));
assert(!matches('民族路129巷','民族路1129巷14號'));
assert(!matches('民族路129巷5弄','民族路129巷15弄14號'));
assert(!matches('民族路129巷5弄','民族路129巷6弄14號'));
assert(matches('民族路129巷5弄','民族路129巷５弄14號',false));
assert(!matches('民族路','新民族路14號'));
assert(matches(' 民族路１２９巷 ','彰化縣彰化市民族路１２９巷１４號'));
assert.throws(()=>roadSearchPattern('民族路.*'));
assert.throws(()=>roadSearchPattern('民族路5弄129巷'));
console.log('Road search regression cases passed');
